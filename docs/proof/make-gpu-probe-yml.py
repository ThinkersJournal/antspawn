"""Generate docs/proof/gpu-probe.yml from docs/proof/gpu-probe.ps1 so the workflow runs the exact tested text. Usage: python3 -I make-gpu-probe-yml.py [label]"""
import pathlib, sys
here = pathlib.Path(__file__).resolve().parent
label = sys.argv[1] if len(sys.argv) > 1 else 'antspawn-s1'
body = (here / 'gpu-probe.ps1').read_text(encoding='utf-8').replace('\r\n', '\n')
# drop the leading comment block and the param line: each step sets $Control itself
lines = [l for l in body.split('\n') if not l.startswith('#') and not l.startswith('param(')]
code = '\n'.join(lines).strip('\n')
def step(name, control):
    ind = ' ' * 10
    head = '$Control = [switch]$true\n' if control else '$Control = [switch]$false\n'
    return f"      - name: {name}\n        shell: pwsh\n        run: |\n" + '\n'.join(ind + l if l else '' for l in (head + code).split('\n')) + '\n'
out = f"""# Generated by make-gpu-probe-yml.py from gpu-probe.ps1: do not edit by hand. Goes to ThinkersJournal/antspawn-proof as
# .github/workflows/gpu-probe.yml (the PM pushes it; lanes cannot). Board 371, C2 s3: is the GPU usable from a restricted runner account?
name: antspawn-gpu-probe
on: workflow_dispatch
permissions: {{}}

jobs:
  gpu:
    runs-on: [self-hosted, windows, {label}]
    timeout-minutes: 10
    steps:
{step('known-bad control - with the driver tools hidden the probe must FAIL (this step passes only if it did)', True)}{step('positive - the GPU is visible to this account and answers a query', False)}"""
(here / 'gpu-probe.yml').write_text(out, encoding='utf-8', newline='\n')
print('wrote gpu-probe.yml')
